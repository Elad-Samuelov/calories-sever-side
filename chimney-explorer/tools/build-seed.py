"""Builds js/seed.js (built-in Before/After gallery) from seed/manifest.json.
Usage: python3 tools/build-seed.py <folder with original photos>
Composites are split with "crop": "left" | "right" | [x0, y0, x1, y1] (fractions); photos are resized to 1000px."""
import base64, io, json, os, sys
from PIL import Image, ImageOps
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'seed', 'photos')
items = json.load(open(os.path.join(root, 'seed', 'manifest.json')))
out = []
for it in items:
    path = os.path.join(root, 'seed', it['src'])
    if not os.path.exists(path): path = os.path.join(src_dir, it['src'])
    if it.get('video'):
        data = 'data:video/mp4;base64,' + base64.b64encode(open(path, 'rb').read()).decode()
        kind = 'video'
    else:
        im = ImageOps.exif_transpose(Image.open(path)).convert('RGB')
        if it.get('crop'):
            w, h = im.size
            c = it['crop']
            if c == 'left': c = [0, 0, 0.5, 1]
            elif c == 'right': c = [0.5, 0, 1, 1]
            im = im.crop((int(c[0] * w), int(c[1] * h), int(c[2] * w), int(c[3] * h)))
        im.thumbnail((1000, 1000))
        buf = io.BytesIO(); im.save(buf, 'JPEG', quality=70, optimize=True, progressive=True)
        data = 'data:image/jpeg;base64,' + base64.b64encode(buf.getvalue()).decode()
        kind = 'image'
    out.append({'id': it['id'], 'part': it['part'], 'label': it['label'], 'caption': it['caption'], 'kind': kind, 'data': data, **({'credit': it['credit']} if it.get('credit') else {})})
js = '/* Built-in Before/After gallery. Generated by tools/build-seed.py, do not edit by hand. */\nwindow.CX_SEED = ' + json.dumps(out) + ';\n'
open(os.path.join(root, 'js', 'seed.js'), 'w').write(js)
print('js/seed.js: %d items, %.1f MB' % (len(out), len(js) / 1048576))
